import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

export function createCategorySchema(iconNames: readonly string[]) {
  return {
    $schema: 'http://json-schema.org/draft-07/schema#',
    $comment: 'Generated from icons/manifest.json. Do not edit this file.',
    title: 'FYIcons categories',
    type: 'object',
    required: ['categories'],
    additionalProperties: false,
    properties: {
      $schema: { type: 'string' },
      categories: {
        type: 'array',
        description: 'Keyword rules and category definitions in sidebar order.',
        items: {
          type: 'object',
          required: ['id', 'name', 'icon', 'keywords'],
          additionalProperties: false,
          properties: {
            id: {
              type: 'string',
              pattern: '^[a-z0-9]+(?:-[a-z0-9]+)*$',
              not: { enum: ['all', 'uncategorized'] },
              description:
                'Unique category ID. All and Uncategorized are automatic.',
            },
            name: {
              type: 'string',
              pattern: '\\S',
              description: 'Display name used throughout the library.',
            },
            icon: {
              $ref: '#/definitions/iconName',
              description: 'Catalog icon shown next to this category.',
            },
            keywords: {
              type: 'array',
              uniqueItems: true,
              description:
                'Match ANY keyword against complete, consecutive name segments, ignoring case. Optional exactNames also match whole names.',
              items: {
                type: 'string',
                pattern: '^\\s*[a-zA-Z0-9]+(?:[-_\\s]+[a-zA-Z0-9]+)*\\s*$',
                description:
                  'For example, file matches file-add, not profile; arrow-up matches circle-arrow-up-fill. Spaces and underscores also separate segments. New keywords are allowed.',
                examples: [
                  ...new Set(iconNames.flatMap((name) => name.split('-'))),
                ].sort(),
              },
            },
            exactNames: {
              type: 'array',
              uniqueItems: true,
              description:
                'Optional whole-name matches, in addition to keywords. For example, box matches only Box, not BoundingBox or TextBox. Case and separators are normalized.',
              items: {
                anyOf: [
                  { $ref: '#/definitions/iconName' },
                  {
                    type: 'string',
                    pattern: '^\\s*[a-zA-Z0-9]+(?:[-_\\s]+[a-zA-Z0-9]+)*\\s*$',
                  },
                ],
              },
            },
          },
        },
      },
    },
    definitions: {
      iconName: { type: 'string', enum: [...iconNames].sort() },
    },
  };
}

/** Completions depend only on the inventory, so category edits need no schema sync. */
export async function updateCategorySchema(root: string) {
  const manifest = await readFile(
    path.join(root, 'icons/manifest.json'),
    'utf8',
  );
  const icons: { name: string }[] = JSON.parse(manifest).icons;
  const content =
    JSON.stringify(
      createCategorySchema(icons.map(({ name }) => name)),
      null,
      2,
    ) + '\n';
  const file = path.join(root, 'apps/site/public/icon-categories.schema.json');
  if ((await readFile(file, 'utf8').catch(() => null)) !== content)
    await writeFile(file, content);
}
